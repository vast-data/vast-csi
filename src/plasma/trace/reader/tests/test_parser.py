def test_get_header_and_data():
    test_data = b'\x13\x00(\xa5\xce\x0e\x0f\xf7S\x14\x00\x00\x00\x00\x00\x00\x02\xff\xff\xff\xff\x19\x004\x0f\xdb\x0e\x0f\xf7S\x14\x02\x00\x00\x00\x02\x00\x02\x08\x00MODULE_P'

    stream = BytesIO(test_data)
    result = list(get_traces_header_and_data(stream))
    assert result[0][0] == TraceHeader(time=1464785947870537000, job_id=0, info_index=0, severity=2)
    assert result[1][0] == TraceHeader(time=1464785947871350580, job_id=2, info_index=2, severity=2)

def test_parse_params():
    format = 'foo %d bla %s spam %hd'
    test_data = b'\x01\x00\x00\x00\x03\x00ABC\x02\x00\x00\x00'
    assert parse_params(format, test_data) == [1, 'ABC', 2]
